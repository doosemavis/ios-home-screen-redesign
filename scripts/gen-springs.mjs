// Regenerates src/motion/springs.js and src/motion/springs.css from one damped-spring
// model, so the WAAPI constants and the CSS custom properties can never drift apart.
// Run: node scripts/gen-springs.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const STOPS = 48
const DECIMALS = 4

// Spring released from rest at 0 toward 1, in normalized time t ∈ [0, 1].
// zeta < 1 overshoots; zeta = 1 is critically damped (no overshoot).
function springAt(t, { zeta, omega }) {
  if (zeta >= 1) return 1 - Math.exp(-omega * t) * (1 + omega * t)
  const damped = omega * Math.sqrt(1 - zeta * zeta)
  const envelope = Math.exp(-zeta * omega * t)
  return 1 - envelope * (Math.cos(damped * t) + ((zeta * omega) / damped) * Math.sin(damped * t))
}

function linearEasing(params) {
  const values = Array.from({ length: STOPS + 1 }, (_, i) => {
    if (i === 0) return 0
    if (i === STOPS) return 1
    return Number(springAt(i / STOPS, params).toFixed(DECIMALS))
  })
  return `linear(${values.join(', ')})`
}

// Snappy: ~4% overshoot, settled by the end. Gentle: critically damped.
const SPRINGS = {
  snappy: { zeta: 0.72, omega: 8.6, ms: 420 },
  gentle: { zeta: 1, omega: 9, ms: 550 },
}

const snappy = linearEasing(SPRINGS.snappy)
const gentle = linearEasing(SPRINGS.gentle)

const js = `// GENERATED by scripts/gen-springs.mjs. Do not edit by hand.
// linear() easings sampled from a damped spring; mirrored in springs.css.
export const SPRING_SNAPPY = '${snappy}'
export const SPRING_GENTLE = '${gentle}'
export const SNAPPY_MS = ${SPRINGS.snappy.ms}
export const GENTLE_MS = ${SPRINGS.gentle.ms}
`

const css = `/* GENERATED by scripts/gen-springs.mjs. Do not edit by hand. Mirrors springs.js. */
:root {
  --spring-snappy: ${snappy};
  --spring-gentle: ${gentle};
  --snappy-ms: ${SPRINGS.snappy.ms}ms;
  --gentle-ms: ${SPRINGS.gentle.ms}ms;
}
`

const out = (name) => fileURLToPath(new URL(`../src/motion/${name}`, import.meta.url))
writeFileSync(out('springs.js'), js)
writeFileSync(out('springs.css'), css)
